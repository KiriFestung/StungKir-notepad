"""StungKir - писательский блокнот на PySide6.

Тексты лежат в ~/StungKir: каждая папка - категория, внутри текстовые файлы.
Панели выдвигаются, если подвести мышь к левому или правому краю окна.
Установка: install.sh (Debian), Flatpak, установщик для Windows - см. README.md.
Лицензия GPL-3.0-or-later. Авторы: KiriFesTung вместе с Claude (Anthropic).

Как устроен код (снизу вверх: нижние модули ничего не знают о верхних):
  config     настройки, пути, темы, дневное расписание и плавный переход
  icons      значки и иконка
  style      оформление Qt
  textutil   слова, падежи, разметка, таблицы, сравнение версий
  storage    запись на диск, кодировки, шифрование, версии, заметки, резервные копии
  lore       справочник мира
  export     сборка книги: PDF, Word, EPUB, текст, шаблоны оформления
  importers  импорт: Word, LibreOffice, RTF, FB2, EPUB, HTML, таблицы Excel и Calc, Scrivener
  snapshots  точки возврата всего проекта и откат
  dialogs    окна-карточки: вопросы, пароль, заметка
  colors     окно «Цвета и темы»: все цвета, образец, контраст, дневная тема
  crutches   мои штампы: слова-костыли автора, подсветка, поиск и замена по главам
  replace    найти и заменить во всех главах, с падежами
  presence   кто в какой главе
  deadline   дедлайн книги
  templates  шаблоны карточек справочника
  rhythm     ритм главы: длина предложений
  timeline   хронология мира
  speech     чтение вслух
  speakers   кто говорит: проверка реплик и сколько говорит каждый
  dice       объёмные кубики, монетка и «Рандомайзеры»
  dicetable  стол для бросков: кубики из кости, металла и дуба, монетка на стол
  roulette   рулетка с писательскими вызовами
  antistress антистресс: пупырка, мячик, спиннер, песок, тумблеры
  covers     обложки категорий
  worldkit   заготовки для мира: бестиарий, государства и прочее
  preview    как увидит читатель: книга, телефон, читалка
  sounds     звуки: кубики, монетка, рулетка, машинка (играет системная программа)
  safety     запасной файл, аварийное сохранение, страховка от стирания, один запуск
  trash      своя корзина на 30 дней
  conflicts  конфликты синхронизации и не-текстовые файлы
  corkboard  пробковая доска: карточки где угодно, булавки и нитки
  sample     пример-проект для первого запуска
  panels     главное окно: панели, меню «Ещё», строки поиска
  markup     главное окно: знаки, *курсив*, **жирный**, ударение
  windows    статистика, сборка книги, настройки, версии
  widgets    мелкие виджеты: цели, ласка в колесе, кубики, панели
  editor     поле текста и подсветка, заметки на полях, панель «рядом»
  table      таблица
  board      доска сюжета
  files, search, world, progress, security, project - части главного окна
  window     главное окно целиком
  app        запуск
  tests      автотесты: python3 -m stungkir --test
"""

